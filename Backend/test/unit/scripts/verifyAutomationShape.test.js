import { describe, it, expect } from 'vitest';
import { deflateSync } from 'node:zlib';

import {
  classifyPdf,
  foreignAttachments,
  pdfTextVolume,
  summariseRun,
} from '../../../scripts/verifyAutomationShape.mjs';

/**
 * A minimal PDF body: one Flate-compressed content stream holding `ops`.
 * Enough for pdfTextVolume, which only ever reads content streams.
 */
function pdfWith(ops) {
  const body = deflateSync(Buffer.from(ops, 'latin1'));
  return Buffer.concat([
    Buffer.from('%PDF-1.7\n1 0 obj\n<< /Length 0 >>\nstream\n', 'latin1'),
    body,
    Buffer.from('\nendstream\nendobj\n%%EOF', 'latin1'),
  ]);
}

describe('pdfTextVolume', () => {
  it('counts text in literal-string show operators', () => {
    expect(pdfTextVolume(pdfWith('BT /F1 12 Tf (Jane Smith) Tj ET'))).toBeGreaterThan(0);
  });

  it('counts text in the hex strings pdfme emits for subset fonts', () => {
    // The generator embeds subset fonts, so the real invoices are hex, not
    // ASCII — a checker that only understood literals would call them blank.
    expect(pdfTextVolume(pdfWith('BT <00480065> Tj ET'))).toBeGreaterThan(0);
  });

  it('reports zero for a page that draws lines and boxes but no text', () => {
    // The failure this whole check exists for: a rendered template with every
    // rule and heading box in place and not one value on it.
    expect(pdfTextVolume(pdfWith('0 0 595 842 re f 100 700 m 400 700 l S'))).toBe(0);
  });

  it('survives a stream it cannot inflate rather than throwing', () => {
    const broken = Buffer.from('%PDF-1.7\nstream\nnot-deflate-data\nendstream\n%%EOF', 'latin1');
    expect(pdfTextVolume(broken)).toBe(0);
  });
});

describe('classifyPdf', () => {
  it.each([
    ['jpjztrn14pJ/monthly-statements/Jane-Smith_January_2025_Statement.pdf', 'statement'],
    ['o24sGM1FoST/NDIS-invoices/INV-1008.pdf', 'invoice'],
    ['jpjztrn14pJ/Participant-invoices/INV-1004.pdf', 'invoice'],
  ])('reads %s as a %s', (path, kind) => {
    expect(classifyPdf(path)).toBe(kind);
  });
});

describe('foreignAttachments', () => {
  const url = (board, name) =>
    `https://host/api/local-files/output/55390/${board}/NDIS-invoices/${name}.pdf`;

  it('finds none when every attachment belongs to the email\'s own board', () => {
    expect(
      foreignAttachments({ boardId: 'board-a', attachments: [url('board-a', 'INV-1')] }),
    ).toEqual([]);
  });

  it('names an attachment generated by another board', () => {
    // The cross-board bleed: one board's email carrying another's invoices.
    const stray = url('board-b', 'INV-9');
    expect(
      foreignAttachments({ boardId: 'board-a', attachments: [url('board-a', 'INV-1'), stray] }),
    ).toEqual([stray]);
  });

  it('is not fooled by a percent-encoded path', () => {
    const encoded = `https://host/api/local-files/output/55390/board-b/NDIS-invoices/INV-1006-ISO%2B%E2%84%A2-Mike.pdf`;
    expect(foreignAttachments({ boardId: 'board-a', attachments: [encoded] })).toEqual([encoded]);
  });

  it('treats an email with no attachments as clean', () => {
    expect(foreignAttachments({ boardId: 'board-a', attachments: [] })).toEqual([]);
  });
});

describe('summariseRun', () => {
  const pdf = (file, textChars) => ({ file, textChars, kind: classifyPdf(file) });

  it('passes a run whose PDFs all carry text and whose emails stay on their board', () => {
    const summary = summariseRun({
      pdfs: [
        pdf('b1/NDIS-invoices/INV-1.pdf', 2600),
        pdf('b1/monthly-statements/Jane_Statement.pdf', 48000),
      ],
      emails: [{ file: 'e1.json', boardId: 'b1', attachments: [] }],
    });

    expect(summary.ok).toBe(true);
    expect(summary.counts).toEqual({ pdfs: 2, invoices: 1, statements: 1, emails: 1 });
    expect(summary.blankPdfs).toEqual([]);
  });

  it('fails the run when any PDF rendered without text', () => {
    const summary = summariseRun({
      pdfs: [pdf('b1/NDIS-invoices/INV-1.pdf', 0)],
      emails: [],
    });

    expect(summary.ok).toBe(false);
    expect(summary.blankPdfs).toEqual(['b1/NDIS-invoices/INV-1.pdf']);
  });

  it('fails the run when an email carries another board\'s document', () => {
    const summary = summariseRun({
      pdfs: [pdf('b1/NDIS-invoices/INV-1.pdf', 2600)],
      emails: [{
        file: 'e1.json',
        boardId: 'b1',
        attachments: ['https://host/api/local-files/output/55390/b2/NDIS-invoices/INV-9.pdf'],
      }],
    });

    expect(summary.ok).toBe(false);
    expect(summary.bleedingEmails).toEqual(['e1.json']);
  });

  it('fails a run that produced nothing at all, rather than reporting a clean sweep', () => {
    // Zero PDFs passes every "none are blank" check trivially; a tick that
    // generated nothing is the outcome most worth catching.
    expect(summariseRun({ pdfs: [], emails: [] }).ok).toBe(false);
  });
});
